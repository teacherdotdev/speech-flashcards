/** An ARASAAC picture and the part of speech of its matching keyword. */
interface Picture {
  id: number;
  /**
   * ARASAAC keyword type: 2 noun, 3 verb, 4 adjective or adverb. The others
   * are names and pronouns (1), social words like "hello" (5) and little words
   * like "of" (6), which don't make picture cards.
   */
  type: number;
  /** In ARASAAC's core vocabulary for communication boards: everyday words. */
  aac: boolean;
}

interface ArasaacResult {
  _id: number;
  sex: boolean;
  violence: boolean;
  aac: boolean;
  keywords: { keyword: string; type: number }[];
}

/** The best picture whose keyword is exactly `word`, or null if there's none. */
async function findPicture(word: string): Promise<Picture | null> {
  const response = await fetch(
    `https://api.arasaac.org/v1/pictograms/en/search/${encodeURIComponent(word)}`,
  );
  if (response.status === 404) return null;
  if (!response.ok)
    throw new Error(`ARASAAC "${word}": HTTP ${response.status}`);
  const results = ((await response.json()) as ArasaacResult[]).filter(
    (result) => !result.sex && !result.violence,
  );
  // Prefer a picture whose main keyword is the word: for "den", the picture
  // of a den rather than one of a warren that also lists "den".
  const match =
    results.find((r) => r.keywords[0]?.keyword.toLowerCase() === word) ??
    results.find((r) =>
      r.keywords.some((k) => k.keyword.toLowerCase() === word),
    );
  if (!match) return null;
  const keyword = match.keywords.find((k) => k.keyword.toLowerCase() === word);
  return { id: match._id, type: keyword?.type ?? 0, aac: match.aac };
}

async function findPictures(
  words: string[],
): Promise<Map<string, Picture | null>> {
  const file = path.join(DATA, "arasaac.json");
  const saved: Record<string, Picture | null> = existsSync(file)
    ? await Bun.file(file).json()
    : {};
  const todo = words.filter((word) => !(word in saved));
  if (todo.length > 0)
    console.log(`Looking up ${todo.length} words on ARASAAC…`);
  // A few requests at a time, to be gentle with ARASAAC's free API.
  const queue = [...todo];
  await Promise.all(
    Array.from({ length: 6 }, async () => {
      for (let word = queue.shift(); word; word = queue.shift()) {
        saved[word] = await findPicture(word);
      }
    }),
  );
  await Bun.write(file, JSON.stringify(saved, null, 1));
  return new Map(words.map((word) => [word, saved[word]]));
}

interface Candidate {
  word: string;
  note?: string;
  picture: Picture | null;
  syllables: number;
}

/**
 * Nouns first (easiest to picture), then verbs, adjectives and the rest; within
 * those, everyday words, then shorter words.
 */
function rank(a: Candidate, b: Candidate): number {
  const order = (c: Candidate) => [2, 3, 4].indexOf(c.picture?.type ?? 0) >>> 0;
  const everyday = (c: Candidate) => (c.picture?.aac ? 0 : 1);
  return (
    order(a) - order(b) ||
    everyday(a) - everyday(b) ||
    a.syllables - b.syllables ||
    a.word.localeCompare(b.word)
  );
}

function camelCase(id: string): string {
  return id.replace(/-(\w)/g, (_, letter: string) => letter.toUpperCase());
}

function packFile(sound: SoundDefinition, cards: Map<Position, Candidate[]>) {
  const lines = [
    GENERATED,
    "// Dale-Chall words with the sound in each position and an ARASAAC picture.",
    'import type { SoundPack } from "#lib/types.ts";',
    "",
    `export const ${camelCase(sound.id)}: SoundPack = {`,
    `  id: "${sound.id}",`,
    `  name: "${sound.name}",`,
    "  cards: {",
  ];
  for (const [position, candidates] of cards) {
    const shown = candidates.slice(0, PER_POSITION);
    lines.push(`    ${position}: [`);
    for (const c of shown) {
      const note = c.note ? ` // ${c.note}` : "";
      lines.push(
        `      { word: "${c.word}", pictogram: ${c.picture!.id} },${note}`,
      );
    }
    const more = candidates.slice(PER_POSITION).map((c) => c.word);
    if (more.length > 0) lines.push(`      // Also: ${more.join(", ")}`);
    lines.push("    ],");
  }
  lines.push("  },", "};", "");
  return lines.join("\n");
}

const escape = (text: string) =>
  text.replace(
    /[&<>"]/g,
    (c) => `&${{ "&": "amp", "<": "lt", ">": "gt", '"': "quot" }[c]};`,
  );

function reviewPage(
  packs: {
    sound: SoundDefinition;
    cards: Map<Position, Candidate[]>;
    noPicture: Candidate[];
  }[],
) {
  const sections = packs.map(({ sound, cards, noPicture }) => {
    const positions = [...cards].map(([position, candidates]) => {
      const figures = candidates
        .slice(0, PER_POSITION)
        .map(
          (c) =>
            `<figure><img loading="lazy" alt="" src="https://static.arasaac.org/pictograms/${c.picture!.id}/${c.picture!.id}_300.png"><figcaption>${escape(c.word)}${c.note ? ` <small>${escape(c.note)}</small>` : ""}</figcaption></figure>`,
        )
        .join("");
      return `<h3>${position} <small>${candidates.length} words</small></h3><div class="grid">${figures}</div>`;
    });
    const missing = noPicture.length
      ? `<details><summary>${noPicture.length} words with no ARASAAC picture</summary><p>${noPicture.map((c) => escape(c.word)).join(", ")}</p></details>`
      : "";
    return `<section id="${sound.id}"><h2>${escape(sound.name)}</h2>${positions.join("")}${missing}</section>`;
  });
  const nav = packs
    .map(({ sound }) => `<a href="#${sound.id}">${escape(sound.name)}</a>`)
    .join(" · ");
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Sound Pack Words</title>
<style>
body { font: 16px/1.4 system-ui, sans-serif; margin: 0 auto; max-width: 72rem; padding: 1rem; background: #fff; color: #222; }
h2 { margin-top: 2.5rem; border-bottom: 2px solid #ddd; } h3 { text-transform: capitalize; } small { color: #777; font-weight: normal; }
.grid { display: grid; grid-template-columns: repeat(auto-fill, minmax(7.5rem, 1fr)); gap: .75rem; }
figure { margin: 0; border: 1px solid #ddd; border-radius: .5rem; padding: .5rem; text-align: center; }
img { width: 100%; aspect-ratio: 1; object-fit: contain; }
footer { margin-top: 3rem; font-size: .85rem; color: #666; }
</style></head><body>
<h1>Sound pack words</h1>
<p>Words from the Dale-Chall list (words most 4th graders know), sorted by sound and position using the CMU Pronouncing Dictionary. The first ${PER_POSITION} in each position are in the app; nouns come first.</p>
<nav>${nav}</nav>
${sections.join("\n")}
<footer>The pictographic symbols used are the property of the Government of Aragón and have been created by Sergio Palao for <a href="https://arasaac.org">ARASAAC</a>, that distributes them under Creative Commons License BY-NC-SA.</footer>
</body></html>
`;
}


/**
 * Words left out of one pack only: "these" and "those" are fine for practicing
 * TH, which has few other words, but not as Z cards.
 */
const NOT_IN: Record<string, string[]> = { z: ["these", "those"] };

/**
 * Words whose best ARASAAC match isn't the picture children should see, and
 * the picture to use instead: "chest" matches a bare-chest anatomy drawing.
 */
const PICTURE_FOR: Record<string, number> = {
  chest: 5966,
  // A gift, not a clock for "the present".
  present: 25381,
};

/**
 * Everyday words that aren't on the Dale-Chall list but that a pack needs:
 * the list has no words that start with Z.
 */
const EXTRA_WORDS = "zebra zero zigzag zipper zoo zucchini".split(" ");

const { words } = await loadPronunciations(EXTRA_WORDS);

const ENDINGS: [string, string[][]][] = [
  ["s", [["S"], ["Z"], ["IH0", "Z"], ["AH0", "Z"]]],
  ["ed", [["D"], ["T"], ["IH0", "D"], ["AH0", "D"]]],
  ["ing", [["IH0", "NG"]]],
];

/**
 * "cats", "glasses", "berries", "played" and "building" are other words plus
 * an ending. Speech therapists avoid them for final sounds, since the sound is
 * then the ending rather than part of the word.
 */
function hasEnding(word: string, main: Pronunciation): boolean {
  return ENDINGS.some(([spelling, sounds]) => {
    if (!word.endsWith(spelling)) return false;
    const cut = word.slice(0, -spelling.length);
    // cat|s, glass|es, berrie|s -> berry, carri|ed -> carry, mak|ing -> make,
    // runn|ing -> run
    const stems = [
      cut,
      cut.slice(0, -1),
      `${cut}e`,
      `${cut.slice(0, -1)}y`,
      `${cut.slice(0, -2)}y`,
    ];
    return stems.some((stem) =>
      words
        .get(stem)
        ?.some((pronunciation) =>
          sounds.some(
            (ending) => [...pronunciation, ...ending].join() === main.join(),
          ),
        ),
    );
  });
}

const placed = SOUNDS.map((sound) => ({
  sound,
  words: [...words].flatMap(([word, [main, ...others]]) => {
    if (LEFT_OUT.has(word) || HARD_TO_PICTURE.has(word)) return [];
    if (NOT_IN[sound.id]?.includes(word)) return [];
    // Use each word's main pronunciation, e.g. "read" as R EH1 D.
    const placement = sound.place(main);
    if (!placement) return [];
    if (placement.position === "final" && hasEnding(word, main)) return [];
    // Leave out words like "tear": the rip has vocalic R "air" but the
    // crying has "ear", and its picture may show either.
    const same = (other: Pronunciation) =>
      JSON.stringify(sound.place(other)) === JSON.stringify(placement);
    if (!others.every(same)) return [];
    return [{ word, ...placement, syllables: main.filter(isVowel).length }];
  }),
}));

const pictures = await findPictures([
  ...new Set(placed.flatMap((p) => p.words.map((w) => w.word))),
]);
for (const [word, id] of Object.entries(PICTURE_FOR)) {
  const picture = pictures.get(word);
  if (picture) pictures.set(word, { ...picture, id });
}

const packs = [];
for (const { sound, words: found } of placed) {
  const cards = new Map<Position, Candidate[]>();
  const noPicture: Candidate[] = [];
  for (const position of POSITIONS) {
    const seen = new Set<number>();
    const candidates: Candidate[] = [];
    for (const w of found.filter((w) => w.position === position)) {
      const candidate = { ...w, picture: pictures.get(w.word) ?? null };
      if (!candidate.picture) noPicture.push(candidate);
      else if (![2, 3, 4].includes(candidate.picture.type)) continue;
      // "good-by" and "good-bye" share a picture; keep one.
      else if (!seen.has(candidate.picture.id)) {
        seen.add(candidate.picture.id);
        candidates.push(candidate);
      }
    }
    if (candidates.length > 0) cards.set(position, candidates.sort(rank));
  }
  packs.push({ sound, cards, noPicture });
  const counts = POSITIONS.map((p) => `${p} ${cards.get(p)?.length ?? 0}`);
  const file = path.join(PACKS_FOLDER, `${sound.id}.ts`);
  const handMade =
    existsSync(file) && !(await Bun.file(file).text()).startsWith(GENERATED);
  if (handMade) {
    console.log(`${sound.name.padEnd(12)} kept (made by hand)`);
    continue;
  }
  await Bun.write(file, packFile(sound, cards));
  console.log(`${sound.name.padEnd(12)} ${counts.join(", ")}`);
}
await Bun.write(path.join(DATA, "review.html"), reviewPage(packs));

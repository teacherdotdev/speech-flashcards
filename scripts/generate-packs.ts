/** Cards per position; the rest are listed in a comment to swap in by hand. */
const PER_POSITION = 20;

/** Where a word has the pack's sound, and an optional label such as "ar" or "st". */
type Placement = { position: Position; note?: string } | undefined;

interface SoundDefinition {
  id: string;
  name: string;
  place: (p: Pronunciation) => Placement;
}

const isVowel = (phoneme?: string) =>
  phoneme !== undefined && /\d$/.test(phoneme);
const unstressed = (phoneme = "") => phoneme.replace(/\d$/, "");
const isStressed = (phoneme?: string) =>
  phoneme !== undefined && /[12]$/.test(phoneme);

/**
 * Whether the T at `i` in the middle of a word sounds like a T. Americans say
 * the T in "water", "city" and "party" as a quick D-like tap, swallow it before
 * N ("button", "lightning") and often drop it after N ("winter"). It stays a T
 * before a stressed vowel ("hotel", "potato"), after another consonant
 * ("sister", "doctor") and before R ("mattress").
 */
function clearT(p: Pronunciation, i: number): boolean {
  const [before, after] = [p[i - 1], p[i + 1]];
  if (!isVowel(after)) return after === "R";
  if (isStressed(after)) return true;
  return !isVowel(before) && before !== "N" && before !== "R";
}

/**
 * A single consonant. Initial: the first sound, followed by a vowel ("sun", not
 * "star", which is a blend). Final: the last sound, after a vowel or vowel + R
 * ("bus", "horse", not "nest"). Medial: anywhere with vowels on both sides of it
 * in the word and a vowel right next to it ("basket").
 */
function consonant(target: string): SoundDefinition["place"] {
  // An L right after an R sound ("girl", "early") is practiced as its own
  // "RL" sound rather than as L.
  const afterR = (before?: string) =>
    target === "L" && (before === "R" || unstressed(before) === "ER");
  return (p) => {
    if (p[0] === target && isVowel(p[1])) return { position: "initial" };
    const last = p.length - 1;
    const before = p[last - 1];
    const afterVowel =
      isVowel(before) || (before === "R" && isVowel(p[last - 2]));
    // "AH0 L" is the L at the end of "apple", which isn't practiced as final L.
    const syllabicL = target === "L" && before === "AH0";
    if (p[last] === target && afterVowel && !syllabicL && !afterR(before)) {
      return { position: "final" };
    }
    const medial = p.some(
      (phoneme, i) =>
        phoneme === target &&
        i > 0 &&
        i < last &&
        p.slice(0, i).some(isVowel) &&
        p.slice(i + 1).some(isVowel) &&
        (isVowel(p[i - 1]) || isVowel(p[i + 1])) &&
        !afterR(p[i - 1]) &&
        (target !== "T" || clearT(p, i)),
    );
    if (medial) return { position: "medial" };
  };
}

/** R before a vowel ("rabbit", "carrot"). R after a vowel is vocalic R. */
function consonantR(p: Pronunciation): Placement {
  if (p[0] === "R" && isVowel(p[1])) return { position: "initial" };
  const i = p.findIndex(
    (phoneme, i) =>
      phoneme === "R" && isVowel(p[i + 1]) && p.slice(0, i).some(isVowel),
  );
  if (i === -1) return;
  // Some lists count the R in "carrot" or "orange" as vocalic R instead.
  return {
    position: "medial",
    note: isVowel(p[i - 1]) ? "between vowels" : "blend",
  };
}

const VOCALIC_R: Record<string, string> = {
  AA: "ar",
  AO: "or",
  OW: "or",
  UH: "or",
  EH: "air",
  EY: "air",
  AE: "air",
  IH: "ear",
  IY: "ear",
  AY: "ire",
  AW: "our",
};

/** "er" sounds (ER in CMUdict) and a vowel followed by R with no vowel after it. */
function vocalicR(p: Pronunciation): Placement {
  const found: { start: number; end: number; note: string }[] = [];
  p.forEach((phoneme, i) => {
    const before = unstressed(p[i - 1]);
    // "around" is ER0 AW1 N D: an unstressed ER before a vowel is really R + vowel.
    if (phoneme === "ER0" && isVowel(p[i + 1])) return;
    if (unstressed(phoneme) === "ER") {
      // "fire" is F AY1 ER0 and "flower" is F L AW1 ER0.
      const joined = before === "AY" || before === "AW";
      found.push({
        start: joined ? i - 1 : i,
        end: i,
        note: joined ? VOCALIC_R[before] : "er",
      });
    } else if (phoneme === "R" && isVowel(p[i - 1]) && !isVowel(p[i + 1])) {
      found.push({ start: i - 1, end: i, note: VOCALIC_R[before] ?? "er" });
    }
  });
  const initial = found.find((r) => r.start === 0);
  if (initial) return { position: "initial", note: initial.note };
  const final = found.find((r) => r.end === p.length - 1);
  if (final) return { position: "final", note: final.note };
  if (found[0]) return { position: "medial", note: found[0].note };
}

const LETTERS: Record<string, string> = { TH: "th", SH: "sh" };
const spell = (phonemes: string[]) =>
  phonemes.map((x) => LETTERS[x] ?? x.toLowerCase()).join("");

/** Word-initial clusters, e.g. S + one of "PTKMNLW" for S-blends. */
function blend(
  first: string[],
  second: string[],
  finalBlends: string[][] = [],
): SoundDefinition["place"] {
  return (p) => {
    if (first.includes(p[0]) && second.includes(p[1])) {
      const cluster = p.slice(0, p.findIndex(isVowel));
      return { position: "initial", note: spell(cluster) };
    }
    const end = finalBlends.find(
      (cluster) =>
        p.slice(-cluster.length).join() === cluster.join() &&
        isVowel(p[p.length - cluster.length - 1]),
    );
    if (end) return { position: "final", note: spell(end) };
  };
}

